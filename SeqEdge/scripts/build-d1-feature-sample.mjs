#!/usr/bin/env node

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SAMPLE_ACCESSIONS = [
  'GCA_000411415.1',
  'GCA_000421325.1',
];

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalogPath = path.join(projectRoot, 'src', 'generated', 'release-catalog.json');
const outputRoot = path.join(projectRoot, 'examples', 'd1-feature-catalog');
const schemaPath = path.join(outputRoot, 'schema.sql');
const seedPath = path.join(outputRoot, 'sample-data.sql');

function sqlText(value) {
  return value === null || value === undefined
    ? 'NULL'
    : `'${String(value).replaceAll("'", "''")}'`;
}

function sqlNumber(value) {
  return typeof value === 'number' && Number.isFinite(value) ? String(value) : 'NULL';
}

function relativeAsset(asset) {
  return asset ? `objects/${asset}` : null;
}

function normalizedSearchTokens(genome) {
  const values = [
    genome.accession,
    genome.organismName,
    genome.strain,
    genome.domain,
    genome.phylum,
    genome.className,
    genome.orderName || genome.order,
    genome.family,
    genome.genus,
  ];
  const tokens = new Set();
  for (const value of values) {
    for (const token of String(value || '').toLocaleLowerCase().normalize('NFKC').split(/[^\p{L}\p{N}_.-]+/u)) {
      if (token) tokens.add(token.slice(0, 200));
    }
  }
  return [...tokens].sort();
}

function referenceStorage(genome) {
  return {
    layout: 'individual-v1',
    files: {
      fasta: relativeAsset(genome.assets.fasta),
      fai: relativeAsset(genome.assets.fastaFai),
      gzi: relativeAsset(genome.assets.fastaGzi),
      metadata: relativeAsset(genome.assets.metadata),
    },
  };
}

function genomeValues(releaseId, genome) {
  return [
    releaseId,
    genome.accession,
    genome.organismName,
    genome.strain,
    genome.domain,
    genome.phylum,
    genome.className,
    genome.orderName || genome.order,
    genome.family,
    genome.genus,
    genome.genomeSource,
    genome.assemblyLevel,
    genome.genomeSizeBp,
    genome.gcContent,
    genome.contigCount,
    genome.completeness,
    genome.contamination,
    genome.defaultLocus,
    genome.primarySequence,
    JSON.stringify(referenceStorage(genome)),
  ];
}

function promoterFeatureValues(releaseId, genome) {
  return [
    releaseId,
    genome.accession,
    'promoter',
    'prediction',
    'peak',
    genome.predictedPromoterCount,
    'ready',
    1,
    'rapptor',
    'unrecorded',
    JSON.stringify({ catalogRelease: releaseId }),
    relativeAsset(genome.assets.predictedPromoters),
    relativeAsset(genome.assets.predictedPromotersIndex),
    '{}',
  ];
}

function sqlTuple(values) {
  return `(${values.map((value) => typeof value === 'number' ? sqlNumber(value) : sqlText(value)).join(', ')})`;
}

async function main() {
  const [schema, rawCatalog] = await Promise.all([
    readFile(schemaPath, 'utf8'),
    readFile(catalogPath, 'utf8'),
  ]);
  if (!schema.includes('CREATE TABLE feature_sets')) throw new Error('Sample schema is missing feature_sets.');

  const catalog = JSON.parse(rawCatalog);
  const byAccession = new Map(catalog.genomes.map((genome) => [genome.accession, genome]));
  const genomes = SAMPLE_ACCESSIONS.map((accession) => {
    const genome = byAccession.get(accession);
    if (!genome) throw new Error(`Sample accession is missing from the catalog: ${accession}`);
    return genome;
  });
  const releaseId = catalog.release.id;
  const featureSummary = {
    promoter: {
      genomeCount: genomes.length,
      featureCount: genomes.reduce((sum, genome) => sum + genome.predictedPromoterCount, 0),
    },
    totalExperimentalGenomes: genomes.filter((genome) => (genome.experimentalDatasetCount || 0) > 0 || genome.experimentalTssCount > 0 || (genome.experimentalPromoterCount || 0) > 0).length,
    totalEvidencePublications: 0,
  };

  const lines = [
    '-- Generated by scripts/build-d1-feature-sample.mjs.',
    '-- Values are extracted from src/generated/release-catalog.json.',
    '',
    'INSERT INTO releases (release_id, source_release_id, release_date, generated_at, description, storage_layout, hf_repository, hf_revision, release_asset_base_url, manifest_index_path, total_genomes, feature_summary_json)',
    `VALUES ${sqlTuple([
      releaseId,
      null,
      catalog.release.date,
      catalog.release.generatedAt,
      'Two-genome example backed by the SeqEdge Hugging Face pilot',
      'individual-v1',
      'liurulong/bacterial-promoter-genomes-pilot',
      'main',
      `https://huggingface.co/datasets/liurulong/bacterial-promoter-genomes-pilot/resolve/main/releases/${releaseId}`,
      null,
      genomes.length,
      JSON.stringify(featureSummary),
    ])};`,
    '',
    `INSERT INTO portal_state (singleton, active_release_id) VALUES (1, ${sqlText(releaseId)});`,
    '',
    'INSERT INTO genomes (release_id, accession, organism_name, strain, domain, phylum, class_name, order_name, family, genus, genome_source, assembly_level, genome_size_bp, gc_content, contig_count, completeness, contamination, default_locus, primary_sequence, reference_storage_json) VALUES',
    `${genomes.map((genome) => sqlTuple(genomeValues(releaseId, genome))).join(',\n')};`,
    '',
    'INSERT INTO feature_sets (release_id, accession, feature_type, evidence_type, count_unit, feature_count, status, is_default, source_id, source_version, provenance_json, data_path, index_path, storage_json) VALUES',
    `${genomes.map((genome) => sqlTuple(promoterFeatureValues(releaseId, genome))).join(',\n')};`,
    '',
  ];

  const searchRows = genomes.flatMap((genome) => normalizedSearchTokens(genome)
    .map((token) => sqlTuple([releaseId, genome.accession, token])));
  lines.push(
    'INSERT OR IGNORE INTO genome_search_terms (release_id, accession, token) VALUES',
    `${searchRows.join(',\n')};`,
    '',
  );

  const ranks = [
    ['source', 'genomeSource'],
    ['domain', 'domain'],
    ['phylum', 'phylum'],
    ['class', 'className'],
    ['order', 'orderName'],
    ['family', 'family'],
    ['genus', 'genus'],
  ];
  const facetRows = new Set();
  for (const genome of genomes) {
    for (const [kind, field] of ranks) {
      const value = genome[field] || (field === 'orderName' ? genome.order : null);
      if (!value) continue;
      const hierarchy = [genome.domain, genome.phylum, genome.className, genome.orderName || genome.order, genome.family];
      const parentCount = kind === 'source' ? 0 : ranks.findIndex(([rank]) => rank === kind) - 1;
      facetRows.add(sqlTuple([
        releaseId,
        kind,
        value,
        ...hierarchy.map((item, index) => index < parentCount ? item || '' : ''),
      ]));
    }
  }
  lines.push(
    'INSERT OR IGNORE INTO facet_options (release_id, kind, value, domain, phylum, class_name, order_name, family) VALUES',
    `${[...facetRows].sort().join(',\n')};`,
    '',
  );

  await mkdir(outputRoot, { recursive: true });
  await writeFile(seedPath, lines.join('\n'));
  console.log(JSON.stringify({
    releaseId,
    output: path.relative(projectRoot, seedPath),
    genomes: genomes.length,
    featureSets: genomes.length,
    promoterFeatures: featureSummary.promoter.featureCount,
  }, null, 2));
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
